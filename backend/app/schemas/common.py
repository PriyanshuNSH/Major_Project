"""
HealthSync AI — Common Schemas & API Envelopes
"""

from datetime import datetime
from typing import Any, Generic, List, Optional, TypeVar
from pydantic import BaseModel, Field

DataT = TypeVar("DataT")


class HealthCheckResponse(BaseModel):
    status: str = Field("healthy", description="Current health status of the service")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="UTC timestamp of the probe")
    app_name: str = Field(..., description="Application name")
    version: str = Field(..., description="Current semantic release version")
    environment: str = Field(..., description="Active runtime environment")


class SuccessEnvelope(BaseModel, Generic[DataT]):
    success: bool = Field(True, description="Indicates operation success")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Response generation timestamp")
    data: DataT = Field(..., description="Encapsulated response payload")


class InvalidParamDetail(BaseModel):
    name: str = Field(..., description="Name or JSON pointer of the invalid field")
    reason: str = Field(..., description="Description of the validation rule violation")
    type: Optional[str] = Field(None, description="Pydantic validation error code")


class ProblemDetailResponse(BaseModel):
    type: str = Field(..., description="URI reference identifying the problem category")
    title: str = Field(..., description="Short, human-readable summary of the problem")
    status: int = Field(..., description="HTTP status code generated by origin server")
    detail: str = Field(..., description="Human-readable explanation specific to this occurrence")
    instance: str = Field(..., description="URI reference identifying the specific occurrence")
    invalid_params: Optional[List[InvalidParamDetail]] = Field(
        None, description="Detailed list of field-level validation errors"
    )


class EngineStatusResponse(BaseModel):
    module_id: str = Field(..., description="Unique module identifier")
    display_name: str = Field(..., description="Human-readable module title")
    model_version: str = Field(..., description="Target model version")
    is_ready: bool = Field(..., description="Whether model artifact is loaded and ready for live ML inference")
    status: str = Field(..., description="'READY' or 'MODEL_UNAVAILABLE'")
    artifact_path: Optional[str] = Field(None, description="Resolved path or relative location of model artifact")
    message: str = Field(..., description="Detailed status description")
